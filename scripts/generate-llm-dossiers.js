#!/usr/bin/env node
/**
 * Automated LLM & AI Dossier Generator
 * Compiles the effective career-positioned release data into canonical
 * machine-readable Markdown and JavaScript files.
 */

const fs = require('node:fs');
const path = require('node:path');
const { D } = require('../data/career-positioning.js');
const { applyNotandiaBranding } = require('../data/notandia-branding.js');
const { buildDossiers } = require('./lib/dossier-generators.js');

applyNotandiaBranding({ D });

const rootDir = path.resolve(__dirname, '..');
buildDossiers(D, rootDir);

const publicDataDir = path.join(rootDir, 'public', 'data');
fs.mkdirSync(publicDataDir, { recursive: true });
const publicSource = `/**
 * GENERATED EFFECTIVE PUBLIC DOSSIER
 * Derived from data/career-positioning.js with the canonical Notandia branding layer. Do not edit this file directly.
 */
const MARIO_DOSSIER = ${JSON.stringify(D, null, 2)};

if (typeof window !== "undefined") {
  window.MARIO_DOSSIER = MARIO_DOSSIER;
}
if (typeof module !== "undefined" && module.exports) {
  module.exports = MARIO_DOSSIER;
}
`;
fs.writeFileSync(path.join(publicDataDir, 'source.js'), publicSource, 'utf8');
console.log('✓ Generated public/data/source.js from the effective recruiter-facing dossier');
